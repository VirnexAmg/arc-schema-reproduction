def step(state, action):
    nxt = state.copy()
    grid = nxt.frame
    aid = int(action["id"])
    pos = _token_box(grid)
    if pos is None:
        return nxt
    x, y = pos

    # Controls move by one 5-pixel tile: up, down, left, right.
    if aid == 1:
        nx, ny = x, y - 5
    elif aid == 2:
        nx, ny = x, y + 5
    elif aid == 3:
        nx, ny = x - 5, y
    elif aid == 4:
        nx, ny = x + 5, y
    else:
        return nxt

    if nx < 0 or ny < 0 or nx + 4 >= len(grid[0]) or ny + 4 >= len(grid):
        return nxt

    # In level 2 the 0/1 tile at the lower-right is a delayed hazard. While the
    # token covers it the glyph is hidden; the next attempted move respawns the
    # token at the checkpoint, restores the glyph and move meter, and consumes
    # one of the three small life marks at bottom-right.
    if (nxt.levels_completed == 1 and x == 49 and y == 45 and
            len(grid[61]) > 62 and grid[61][62] == 8):
        for yy in range(45, 50):
            for xx in range(49, 54):
                grid[yy][xx] = 3
        grid[46][51] = 0
        grid[47][50] = 1
        grid[47][51] = 0
        grid[47][52] = 0
        grid[48][51] = 1
        for yy in range(40, 45):
            for xx in range(29, 34):
                grid[yy][xx] = 12 if yy < 42 else 9
        for yy in (61, 62):
            for xx in range(13, 55):
                grid[yy][xx] = 11
            grid[yy][62] = 3
            grid[yy][63] = 3
        # The lower-left life/status glyph advances one phase on respawn.
        for yy in (55, 56):
            for xx in range(3, 9):
                grid[yy][xx] = 9
        for yy in (59, 60):
            for xx in range(3, 9):
                grid[yy][xx] = 5
            grid[yy][3] = 9
            grid[yy][4] = 9
            grid[yy][7] = 9
            grid[yy][8] = 9
        return nxt

    # Entering the lower patterned chamber in level 2 is a return/recharge
    # portal: it sends the token to the checkpoint, refills the meter, restores
    # the upper patterned dock, and advances the warning/status display.
    meter_empty = (nxt.levels_completed == 1 and
                   not any(grid[61][xx] == 11 for xx in range(len(grid[61]))))
    if meter_empty:
        # Exhaustion outcome is encoded by the bottom-right life display.
        # With multiple 8-marks present (fresh life after an outer reset), the
        # next input is terminal.  In the earlier depleted-life phase it was a
        # checkpoint respawn, which explains both recorded exhaustion events.
        # The warning/status glyph records whether exhaustion is recoverable:
        # a right-hand mark (x=7..8) is terminal, while the earlier left-hand
        # phase produces the checkpoint recovery seen at transition 89.
        fresh_life = (len(grid) > 57 and len(grid[57]) > 7 and
                      grid[57][7] == 9)
        if fresh_life:
            vals = []
            for yy in range(ny, ny + 5):
                for xx in range(nx, nx + 5):
                    vals.append(grid[yy][xx])
            if all(v == 3 for v in vals):
                for yy in range(y, y + 5):
                    for xx in range(x, x + 5):
                        grid[yy][xx] = 3
                for yy in range(ny, ny + 5):
                    for xx in range(nx, nx + 5):
                        grid[yy][xx] = 12 if yy < ny + 2 else 9
            for yy in (61, 62):
                for xx in (56, 57, 59, 60, 62, 63):
                    grid[yy][xx] = 3
            nxt.state = "GAME_OVER"
            return nxt

        for yy in range(y, y + 5):
            for xx in range(x, x + 5):
                grid[yy][xx] = 3
        for yy in range(40, 45):
            for xx in range(29, 34):
                grid[yy][xx] = 12 if yy < 42 else 9
        for yy in (61, 62):
            for xx in range(13, 55):
                grid[yy][xx] = 11
        for yy in (16, 18):
            for xx in range(15, 18):
                grid[yy][xx] = 11
        grid[17][15] = 11
        grid[17][17] = 11
        for yy in (61, 62):
            for xx in range(59, 64):
                if xx != 61:
                    grid[yy][xx] = 3
        for yy in (57, 58):
            for xx in range(3, 9):
                grid[yy][xx] = 5
            grid[yy][7] = 9
            grid[yy][8] = 9
        return nxt

    # An upward activation at the dock completes the maze only after the floor
    # switch has toggled the left status mark off.
    if (aid == 1 and nxt.levels_completed == 0 and x == 34 and y == 15 and
            len(grid) > 57 and grid[57][3] == 5):
        _load_level2(nxt)
        return nxt

    # Ordinary route tiles are color 3.  The patterned upper terminal has a
    # special docking tile at x=34..38,y=15..19: its first row is color 5 and
    # the remaining rows are route-colored.
    vals = []
    for yy in range(ny, ny + 5):
        for xx in range(nx, nx + 5):
            vals.append(grid[yy][xx])
    open_route = all(v == 3 for v in vals)
    # Small color-0/1 glyphs embedded in a route tile are collectibles and do
    # not block entry. The first observed glyph is on tile x=19..23,y=30..34.
    collectible_route = (all(v in (0, 1, 3) for v in vals) and
                         any(v in (0, 1) for v in vals))
    upper_dock = (ny == 15 and nx == 34 and
                  all(grid[15][xx] == 5 for xx in range(34, 39)) and
                  all(grid[yy][xx] == 3 for yy in range(16, 20)
                      for xx in range(34, 39)))
    # Level 2 has a patterned 11-on-3 chamber tile. It is traversable despite
    # not being uniform floor and acts as a recharge dock on entry.
    meter_columns = 0
    if len(grid) > 62:
        for xx in range(len(grid[61])):
            if grid[61][xx] == 11 and grid[62][xx] == 11:
                meter_columns += 1
    recharge_dock = (nxt.levels_completed == 1 and
                     ((nx == 14 and ny == 15) or
                      (nx == 39 and ny == 50 and meter_columns > 2)) and
                     all(v in (3, 11) for v in vals) and any(v == 11 for v in vals))

    if not open_route and not collectible_route and not upper_dock and not recharge_dock:
        # Recorded wall collisions consume a meter step.  Pressing farther up
        # while already docked at the upper terminal is instead a total no-op.
        # The lower patterned chamber rejects entry when only the final meter
        # unit remains, without charging that failed interaction.
        if (nxt.levels_completed == 1 and nx == 39 and ny == 50):
            remaining_here = 0
            for xx in range(len(grid[61])):
                if grid[61][xx] == 11:
                    remaining_here += 1
            if remaining_here <= 2:
                return nxt
        if not (aid == 1 and y == 15):
            # In level 2 a blocked press cannot spend the final two-column
            # meter unit; recorded earlier collisions with more charge do pay.
            remaining = 0
            if len(grid) > 61:
                for xx in range(len(grid[61])):
                    if grid[61][xx] == 11:
                        remaining += 1
            if nxt.levels_completed != 1 or remaining > 2:
                _advance_meter(grid, nxt.levels_completed + 1)
        return nxt

    # Vacated route cells reveal their substrate. The upper dock preserves its
    # color-5 stripe. A stepped-on 0/1 glyph is a floor switch: it is hidden by
    # the token but reappears when the token leaves (rather than being consumed).
    for yy in range(y, y + 5):
        for xx in range(x, x + 5):
            grid[yy][xx] = (5 if nxt.levels_completed == 0 and y == 15 and yy == 15
                            else 3)
    if x == 19 and y == 30:
        grid[y + 1][x + 2] = 0
        grid[y + 2][x + 1] = 1
        grid[y + 2][x + 2] = 0
        grid[y + 2][x + 3] = 0
        grid[y + 3][x + 2] = 1
    if nxt.levels_completed == 1 and x == 49 and y == 45:
        # The lower-right switch is likewise revealed again when vacated.
        grid[y + 1][x + 2] = 0
        grid[y + 2][x + 1] = 1
        grid[y + 2][x + 2] = 0
        grid[y + 2][x + 3] = 0
        grid[y + 3][x + 2] = 1
    # Draw the 5x5 token: two color-12 rows over three color-9 rows.
    for yy in range(ny, ny + 5):
        for xx in range(nx, nx + 5):
            grid[yy][xx] = 12 if yy < ny + 2 else 9

    if recharge_dock:
        # Entering the patterned chamber recharges the ordinary-action meter.
        for yy in (61, 62):
            for xx in range(13, 55):
                grid[yy][xx] = 11
    elif collectible_route:
        if (nxt.levels_completed == 1 and nx == 49 and ny == 45 and
                len(grid[61]) > 62 and grid[61][62] == 8):
            # The lower-right trigger exhausts the meter only while the final
            # bottom-right life mark is still present. After the first respawn,
            # revisiting the glyph still changes the warning display but costs
            # only the normal level-2 meter step.
            # The trigger exhausts the meter while the upper patterned dock is
            # still armed. After that dock has been consumed/erased, the last
            # two-column reserve is preserved.
            upper_armed = False
            for yy in (16, 17, 18):
                for xx in (15, 16, 17):
                    if grid[yy][xx] == 11:
                        upper_armed = True
            if upper_armed:
                for yy in (61, 62):
                    for xx in range(13, 55):
                        grid[yy][xx] = 3
            else:
                _advance_meter(grid, 2)
            for yy in (55, 56):
                for xx in range(3, 9):
                    grid[yy][xx] = 5
                grid[yy][3] = 9
                grid[yy][4] = 9
                grid[yy][7] = 9
                grid[yy][8] = 9
            for yy in (59, 60):
                for xx in range(3, 9):
                    grid[yy][xx] = 9
        elif nxt.levels_completed == 1 and nx == 49 and ny == 45:
            # After the life mark is consumed, revisiting the trigger costs one
            # normal level-2 action while charge remains, but preserves the
            # final two-column reserve and still advances the warning glyph.
            charge_before = 0
            for xx in range(len(grid[61])):
                if grid[61][xx] == 11:
                    charge_before += 1
            if charge_before > 2:
                _advance_meter(grid, 2)
            for yy in (55, 56):
                for xx in range(3, 9):
                    grid[yy][xx] = 5
                grid[yy][3] = 9
                grid[yy][4] = 9
                grid[yy][7] = 9
                grid[yy][8] = 9
            # Warning mark changes side once the remaining meter is low.
            # The first safe revisit has 12 columns before payment and shows
            # the right mark; the later revisit has 6 and shows the left mark.
            remaining = 0
            for xx in range(len(grid[61])):
                if grid[61][xx] == 11:
                    remaining += 1
            # At the final two meter columns the upper warning band becomes
            # fully lit rather than retaining the two separated marks.
            if remaining <= 2:
                for yy in (55, 56):
                    for xx in range(3, 9):
                        grid[yy][xx] = 9
            for yy in (57, 58):
                for xx in range(3, 9):
                    grid[yy][xx] = 5
                if remaining <= 6:
                    grid[yy][3] = 9
                    grid[yy][4] = 9
                else:
                    grid[yy][7] = 9
                    grid[yy][8] = 9
            for yy in (59, 60):
                for xx in range(3, 9):
                    grid[yy][xx] = 9
                if remaining <= 2:
                    grid[yy][5] = 5
                    grid[yy][6] = 5
        elif len(grid) > 58 and len(grid[57]) > 8:
            # Level 1's switch toggles which two-pixel status mark is lit.
            for yy in (57, 58):
                grid[yy][3] = 5
                grid[yy][4] = 5
                grid[yy][7] = 9
                grid[yy][8] = 9
    else:
        _advance_meter(grid, nxt.levels_completed + 1)
    return nxt


def is_goal(state):
    # A level-up is not the game goal: seven levels must be completed.  The
    # prior predicate incorrectly treated arrival in level 2 as success and
    # could not represent continued play after a life reset.
    return state.state == "WIN" or state.levels_completed >= 7

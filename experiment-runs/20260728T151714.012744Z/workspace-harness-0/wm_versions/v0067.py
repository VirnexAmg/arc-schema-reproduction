# Moving-token world model inferred from recorded transitions.
# Helpers available: GridState, find_color, bbox, neighbors4, deepcopy

def _token_box(grid):
    pts = []
    for y in range(len(grid)):
        for x in range(len(grid[y])):
            if grid[y][x] == 12:
                pts.append((x, y))
    if not pts:
        return None
    return (min(p[0] for p in pts), min(p[1] for p in pts))


def _advance_meter(grid, amount=1):
    # Meter cost scales with the current level: level 1 consumes one column
    # per ordinary action, while the observed level-2 actions consume two.
    if len(grid) <= 62:
        return
    w = len(grid[61])
    available = 0
    for x in range(w):
        if grid[61][x] == 11 and grid[62][x] == 11:
            available += 1
    # Ordinary actions can consume the final meter unit; any rejected
    # interaction that preserves it is handled at that interaction site.
    for unused in range(amount):
        for x in range(w):
            if grid[61][x] == 11 and grid[62][x] == 11:
                grid[61][x] = 3
                grid[62][x] = 3
                break



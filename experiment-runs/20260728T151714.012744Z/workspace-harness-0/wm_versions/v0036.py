def step(state, action):
    nxt = state.copy()
    grid = nxt.frame
    aid = int(action["id"])
    pos = _token_box(grid)
    if pos is None:
        return nxt
    x, y = pos

    # Controls move by one 5-pixel tile: up, down, left, right.
    if aid == 1:
        nx, ny = x, y - 5
    elif aid == 2:
        nx, ny = x, y + 5
    elif aid == 3:
        nx, ny = x - 5, y
    elif aid == 4:
        nx, ny = x + 5, y
    else:
        return nxt

    if nx < 0 or ny < 0 or nx + 4 >= len(grid[0]) or ny + 4 >= len(grid):
        return nxt

    # In level 2 the 0/1 tile at the lower-right is a delayed hazard. While the
    # token covers it the glyph is hidden; the next attempted move respawns the
    # token at the checkpoint, restores the glyph and move meter, and consumes
    # one of the three small life marks at bottom-right.
    if (nxt.levels_completed == 1 and x == 49 and y == 45 and
            len(grid[61]) > 62 and grid[61][62] == 8):
        for yy in range(45, 50):
            for xx in range(49, 54):
                grid[yy][xx] = 3
        grid[46][51] = 0
        grid[47][50] = 1
        grid[47][51] = 0
        grid[47][52] = 0
        grid[48][51] = 1
        for yy in range(40, 45):
            for xx in range(29, 34):
                grid[yy][xx] = 12 if yy < 42 else 9
        for yy in (61, 62):
            for xx in range(13, 55):
                grid[yy][xx] = 11
            grid[yy][62] = 3
            grid[yy][63] = 3
        # The lower-left life/status glyph advances one phase on respawn.
        for yy in (55, 56):
            for xx in range(3, 9):
                grid[yy][xx] = 9
        for yy in (59, 60):
            for xx in range(3, 9):
                grid[yy][xx] = 5
            grid[yy][3] = 9
            grid[yy][4] = 9
            grid[yy][7] = 9
            grid[yy][8] = 9
        return nxt

    # An upward activation at the dock completes the maze only after the floor
    # switch has toggled the left status mark off.
    if (aid == 1 and nxt.levels_completed == 0 and x == 34 and y == 15 and
            len(grid) > 57 and grid[57][3] == 5):
        _load_level2(nxt)
        return nxt

    # Ordinary route tiles are color 3.  The patterned upper terminal has a
    # special docking tile at x=34..38,y=15..19: its first row is color 5 and
    # the remaining rows are route-colored.
    vals = []
    for yy in range(ny, ny + 5):
        for xx in range(nx, nx + 5):
            vals.append(grid[yy][xx])
    open_route = all(v == 3 for v in vals)
    # Small color-0/1 glyphs embedded in a route tile are collectibles and do
    # not block entry. The first observed glyph is on tile x=19..23,y=30..34.
    collectible_route = (all(v in (0, 1, 3) for v in vals) and
                         any(v in (0, 1) for v in vals))
    upper_dock = (ny == 15 and nx == 34 and
                  all(grid[15][xx] == 5 for xx in range(34, 39)) and
                  all(grid[yy][xx] == 3 for yy in range(16, 20)
                      for xx in range(34, 39)))
    # Level 2 has a patterned 11-on-3 chamber tile. It is traversable despite
    # not being uniform floor and acts as a recharge dock on entry.
    recharge_dock = (nxt.levels_completed == 1 and nx == 14 and ny == 15 and
                     all(v in (3, 11) for v in vals) and any(v == 11 for v in vals))

    if not open_route and not collectible_route and not upper_dock and not recharge_dock:
        # Recorded wall collisions consume a meter step.  Pressing farther up
        # while already docked at the upper terminal is instead a total no-op.
        if not (aid == 1 and y == 15):
            _advance_meter(grid, nxt.levels_completed + 1)
        return nxt

    # Vacated route cells reveal their substrate. The upper dock preserves its
    # color-5 stripe. A stepped-on 0/1 glyph is a floor switch: it is hidden by
    # the token but reappears when the token leaves (rather than being consumed).
    for yy in range(y, y + 5):
        for xx in range(x, x + 5):
            grid[yy][xx] = (5 if nxt.levels_completed == 0 and y == 15 and yy == 15
                            else 3)
    if x == 19 and y == 30:
        grid[y + 1][x + 2] = 0
        grid[y + 2][x + 1] = 1
        grid[y + 2][x + 2] = 0
        grid[y + 2][x + 3] = 0
        grid[y + 3][x + 2] = 1
    if nxt.levels_completed == 1 and x == 49 and y == 45:
        # The lower-right switch is likewise revealed again when vacated.
        grid[y + 1][x + 2] = 0
        grid[y + 2][x + 1] = 1
        grid[y + 2][x + 2] = 0
        grid[y + 2][x + 3] = 0
        grid[y + 3][x + 2] = 1
        # Leaving the switch advances the middle warning band from its right
        # pair to its left pair.
        for yy in (57, 58):
            for xx in range(3, 9):
                grid[yy][xx] = 5
            grid[yy][3] = 9
            grid[yy][4] = 9

    # Draw the 5x5 token: two color-12 rows over three color-9 rows.
    for yy in range(ny, ny + 5):
        for xx in range(nx, nx + 5):
            grid[yy][xx] = 12 if yy < ny + 2 else 9

    if recharge_dock:
        # Entering the patterned chamber recharges the ordinary-action meter.
        for yy in (61, 62):
            for xx in range(13, 55):
                grid[yy][xx] = 11
    elif collectible_route:
        if (nxt.levels_completed == 1 and nx == 49 and ny == 45 and
                len(grid[61]) > 62 and grid[61][62] == 8):
            # The lower-right trigger exhausts the meter only while the final
            # bottom-right life mark is still present. After the first respawn,
            # revisiting the glyph still changes the warning display but costs
            # only the normal level-2 meter step.
            for yy in (61, 62):
                for xx in range(13, 55):
                    grid[yy][xx] = 3
            for yy in (55, 56):
                for xx in range(3, 9):
                    grid[yy][xx] = 5
                grid[yy][3] = 9
                grid[yy][4] = 9
                grid[yy][7] = 9
                grid[yy][8] = 9
            for yy in (59, 60):
                for xx in range(3, 9):
                    grid[yy][xx] = 9
        elif nxt.levels_completed == 1 and nx == 49 and ny == 45:
            # After the life mark is consumed, revisiting the trigger costs one
            # normal level-2 action and advances the three-band warning glyph.
            _advance_meter(grid, 2)
            for yy in (55, 56):
                for xx in range(3, 9):
                    grid[yy][xx] = 5
                grid[yy][3] = 9
                grid[yy][4] = 9
                grid[yy][7] = 9
                grid[yy][8] = 9
            for yy in (57, 58):
                for xx in range(3, 9):
                    grid[yy][xx] = 5
                grid[yy][7] = 9
                grid[yy][8] = 9
            for yy in (59, 60):
                for xx in range(3, 9):
                    grid[yy][xx] = 9
        elif len(grid) > 58 and len(grid[57]) > 8:
            # Level 1's switch toggles which two-pixel status mark is lit.
            for yy in (57, 58):
                grid[yy][3] = 5
                grid[yy][4] = 5
                grid[yy][7] = 9
                grid[yy][8] = 9
    else:
        _advance_meter(grid, nxt.levels_completed + 1)
    return nxt


def is_goal(state):
    return state.state == "WIN" or state.levels_completed > 0

def decode_rle(rle_list):
    grid = []
    for line in rle_list:
        row = []
        for chunk in line.split(','):
            col_str, count_str = chunk.split(':')
            col = int(col_str)
            count = int(count_str)
            row.extend([col] * count)
        grid.append(row)
    return grid

